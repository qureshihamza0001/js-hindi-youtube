const month = "March"

switch (month) {
    case "Jan":
        console.log("January");
        
        break;
    case "Feb":
        console.log("February");
        
        break;
    case "March":
        console.log("March");
        
        break;
    case "April":
        console.log("April");
        
        break;
    

    default:
        console.log("defaul case match");
        
        break;
}